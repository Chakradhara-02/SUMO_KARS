"""Three explicit stages: offline transitions, online propagation, adjustment."""
import json
import networkx as nx
from .models import State

def offline_rs(config, output=None):
    actions = list(dict.fromkeys([0.0, config['max_acceleration'], max(config['min_acceleration'], -2.0), config['min_acceleration']]))
    table = []
    for velocity in range(int(config['max_speed']) + 1):
        for acceleration in actions:
            nxt = velocity + acceleration * config['dt']
            if config['min_speed'] <= nxt <= config['max_speed']:
                table.append({'v': velocity, 'a': acceleration, 'next_v': nxt,
                              'dx': velocity * config['dt'] + .5 * acceleration * config['dt']**2})
    result = {'actions': actions, 'transitions': table, 'dt': config['dt']}
    if output:
        output.write_text(json.dumps(result, indent=2))
    return result

def propagate(state, acceleration, lane, config):
    dt = config['dt']
    # SUMO speeds are continuous. A fixed -2/-4 action must also be able to
    # stop a vehicle at 0.7 m/s instead of rejecting every braking transition.
    # Reduce braking to stop exactly at this step's end; never reverse motion.
    if acceleration < 0 and state.v > config['min_speed']:
        acceleration = max(acceleration, (config['min_speed']-state.v)/dt)
    v = state.v + acceleration * dt
    if not config['min_speed'] - 1e-8 <= v <= config['max_speed'] + 1e-8:
        return None
    if abs(lane - state.lane) > 1 or not 0 <= lane < config['lanes']:
        return None
    if state.lane_hold > 1e-8 and lane != state.lane:
        return None
    changing = lane != state.lane
    hold = max(0., (config['lane_change_duration'] if changing else state.lane_hold) - dt)
    origin = state.lane if changing else state.lane_origin if hold > 0 else -1
    return State(state.x + state.v * dt + .5 * acceleration * dt**2,
                 max(0., v), lane, state.t + dt, hold, origin)

def online_rs(start, offline, config):
    graph = nx.DiGraph()
    graph.add_node(0, state=start, layer=0)
    layer, counter = [0], 1
    for step in range(1, config['horizon'] + 1):
        bins, next_layer = {}, []
        for parent in layer:
            state = graph.nodes[parent]['state']
            for a in offline['actions']:
                for lane in range(max(0, state.lane-1), min(config['lanes'], state.lane+2)):
                    nxt = propagate(state, a, lane, config)
                    if nxt is None:
                        continue
                    key = (round(nxt.x/config['position_grid']), round(nxt.v/config['velocity_grid']), lane,
                           nxt.lane_hold,nxt.lane_origin)
                    if key in bins:
                        node = bins[key]
                        # Only merge identical continuous states: a grid bin is not a dynamics proof.
                        existing = graph.nodes[node]['state']
                        if abs(existing.x-nxt.x) > 1e-7 or abs(existing.v-nxt.v) > 1e-7:
                            continue
                    else:
                        node = counter
                        counter += 1
                        bins[key] = node
                        next_layer.append(node)
                        graph.add_node(node, state=nxt, layer=step)
                    graph.add_edge(parent, node, acceleration=(nxt.v-state.v)/config['dt'])
        # Preserve coverage of every lane instead of taking the first states
        # generated by loop order (which silently starved the left lane).
        if len(next_layer) > config['max_states']:
            groups = [[n for n in next_layer if graph.nodes[n]['state'].lane == lane]
                      for lane in range(config['lanes'])]
            keep = []
            remaining = config['max_states']
            active = [g for g in groups if g]
            for index, group in enumerate(active):
                quota = min(len(group), remaining // (len(active)-index))
                group.sort(key=lambda n: (graph.nodes[n]['state'].x,graph.nodes[n]['state'].v,
                                          graph.nodes[n]['state'].lane_hold))
                if quota == 1:
                    keep.append(group[len(group)//2])
                elif quota > 1:
                    keep += [group[round(i*(len(group)-1)/(quota-1))] for i in range(quota)]
                remaining -= quota
            graph.remove_nodes_from(set(next_layer)-set(keep))
            next_layer = keep
        layer = next_layer
    return graph

def violates(previous, state, constraint):
    if constraint.kind=='rear_occupancy' and previous.lane==state.lane==constraint.lane and (
            previous.lane_origin<0 and state.lane_origin<0):
        return False
    occupied = {previous.lane,state.lane,previous.lane_origin,state.lane_origin} - {-1}
    if constraint.lane >= 0 and constraint.lane not in occupied:
        return False
    if state.x < constraint.start or previous.x > constraint.end:
        return False
    temporal = constraint.kind in ('spatial_temporal', 'spatial_temporal_speed','rear_occupancy')
    if temporal and (state.t < constraint.begin or previous.t > constraint.finish):
        return False
    if constraint.kind == 'marking':
        return previous.lane != state.lane
    if constraint.kind in ('spatial', 'spatial_temporal','rear_occupancy'):
        return True
    # Check speed throughout the swept interval, including its entry boundary.
    return max(previous.v, state.v) > constraint.speed + 1e-6

def rs_adjustment(raw, constraints):
    graph = raw.copy()
    rejected = []
    for u, v in list(graph.edges):
        a, b = graph.nodes[u]['state'], graph.nodes[v]['state']
        reasons = [c.source or c.kind for c in constraints if violates(a, b, c)]
        if reasons:
            graph.remove_edge(u, v)
            rejected.append({'from': u, 'to': v, 'reasons': reasons})
    if 0 in graph:
        reachable = nx.descendants(graph, 0) | {0}
        graph.remove_nodes_from(set(graph) - reachable)
    return graph, rejected
